import {writeFileSync} from 'node:fs';

// Only this public value is exposed to the browser bundle.
const icpNumber = (process.env.DOCS_ICP_NUMBER ?? '').trim();
writeFileSync(new URL('../src/app/site-config.ts', import.meta.url),
    `// Generated by scripts/build-site-config.mjs before build/start/watch.\nexport const icpNumber = ${JSON.stringify(icpNumber)};\n`);
