import assert from 'node:assert/strict';
import {readFileSync, existsSync} from 'node:fs';
import {join} from 'node:path';
import {JSDOM} from 'jsdom';
import {documentationPages, literal, root} from './docs-model.mjs';
const pages = documentationPages();
const output = join(root, 'docs');
const routes = new Set(pages.map(page => page.route));
const ids = new Map();
const links = [];
for (const page of pages) {
    const html = readFileSync(join(output, page.route, 'index.html'), 'utf8');
    const window = new JSDOM(html).window;
    const document = window.document;
    assert.equal(document.documentElement.lang, page.locale);
    assert(!/<ng-doc-[a-z-]+\b/i.test(html), `Unrendered NgDoc component ${page.route}`);
    assert.equal(document.querySelectorAll('[onclick]').length, 0, `Unbound interactive control ${page.route}`);
    const generated = literal(readFileSync(page.generated, 'utf8'), 'pageContent');
    assert.equal(document.querySelectorAll('.code-variant').length, [...generated.matchAll(/<ng-doc-tab\b/g)].length,
        `Missing code alternatives ${page.route}`);
    assert.equal(document.querySelectorAll('article table').length, [...generated.matchAll(/<table\b/g)].length,
        `Missing tables ${page.route}`);
    assert(document.querySelector('article h1'), `Missing title ${page.route}`);
    assert(document.querySelector('article').textContent.length > 100, `Empty body ${page.route}`);
    assert(document.querySelector('link[rel="canonical"]').href.endsWith(`${page.route}/`));
    assert.equal(document.querySelectorAll('link[hreflang]').length, 2);
    const counterpart = page.locale === 'en' ? 'zh-CN' : 'en';
    assert(document.querySelector(`link[hreflang="${page.locale}"]`).href.endsWith(`${page.route}/`));
    assert(document.querySelector(`link[hreflang="${counterpart}"]`).href.endsWith(`${page.route.replace(`/documentation/${page.locale}/`, `/documentation/${counterpart}/`)}/`));
    assert(document.querySelector(`a[href="/#${page.route}"]`), `Missing legacy hash route ${page.route}`);
    ids.set(page.route, new Set([...document.querySelectorAll('[id]')].map(node => node.id)));
    for (const link of document.querySelectorAll('a[href]')) {
        const href = link.getAttribute('href');
        if (!href.startsWith('/documentation/') && !href.startsWith('#')) continue;
        const url = new URL(href, `https://kotlinorm.com${page.route}/`);
        const target = url.pathname.replace(/\/$/, '');
        if (/^\/documentation\/(en|zh-CN)$/.test(target)) continue;
        links.push({page: page.route, target, fragment: decodeURIComponent(url.hash.slice(1))});
    }
    // Every code alternative and every table generated by NgDoc remains readable without Angular.
    if (html.includes('class="code-variant"')) assert(document.querySelector('.code-variant pre code'));
    window.close();
}
for (const link of links) {
    assert(routes.has(link.target), `Broken static route ${link.target} from ${link.page}`);
    assert(!link.fragment || ids.get(link.target).has(link.fragment), `Broken static anchor ${link.target}#${link.fragment} from ${link.page}`);
}
for (const locale of ['en', 'zh-CN']) {
    const window = new JSDOM(readFileSync(join(output, 'documentation', locale, 'index.html'), 'utf8')).window;
    const document = window.document;
    assert.equal(document.documentElement.lang, locale);
    assert(document.querySelector('meta[name="viewport"]'));
    assert(document.querySelector('link[rel="canonical"]').href.endsWith(`/documentation/${locale}/`));
    assert.equal(document.querySelectorAll('link[hreflang]').length, 2);
    assert.equal(document.querySelectorAll('ul a').length, pages.filter(page => page.locale === locale).length);
    window.close();
}
const indexes = JSON.parse(readFileSync(join(output, 'assets/ng-doc/indexes.json'), 'utf8'));
assert.equal(indexes.length, pages.length);
assert.equal(new Set(indexes.map(index => index.route)).size, pages.length);
const sitemap = readFileSync(join(output, 'sitemap.xml'), 'utf8');
for (const page of pages) assert(sitemap.includes(`${page.route}/</loc>`));
assert(existsSync(join(output, 'assets/static-docs.css')));
assert(readFileSync(join(output, '_redirects'), 'utf8').includes('/documentation/en/getting-started/kmp /documentation/en/getting-started/kmp/index.html 200'));
console.log(`Verified ${pages.length} HTML documents, all local routes/anchors, canonical/alternate metadata, legacy hash links, search index and sitemap.`);
