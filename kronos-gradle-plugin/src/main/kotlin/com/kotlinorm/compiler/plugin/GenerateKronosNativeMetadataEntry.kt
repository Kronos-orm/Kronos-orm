package com.kotlinorm.compiler.plugin

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.provider.Property
import org.gradle.api.provider.ListProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Writes the source-visible Native metadata entry that the compiler plugin
 * fills with static descriptor registrations during Native IR generation.
 */
@CacheableTask
abstract class GenerateKronosNativeMetadataEntry : DefaultTask() {
    @get:Input
    abstract val entryFqName: Property<String>

    @get:Input
    abstract val providerId: Property<String>

    @get:Input
    abstract val additionalEntries: ListProperty<String>

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val dependencyMetadata: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    init { additionalEntries.convention(emptyList()) }

    @TaskAction
    fun generate() {
        val fqName = entryFqName.get()
        val separator = fqName.lastIndexOf('.')
        require(separator > 0 && separator < fqName.lastIndex) {
            "Native metadata entry must be a top-level function fq-name: $fqName"
        }
        val packageName = fqName.substring(0, separator)
        val functionName = fqName.substring(separator + 1)
        require(functionName.matches(Identifier)) {
            "Native metadata entry must be a valid Kotlin identifier: $functionName"
        }
        val entries = readNativeMetadataManifests(dependencyMetadata.files)
        val aggregateName = "${functionName}Dependencies"
        val providerName = "${functionName}Provider"
        val providerLiteral = providerId.get().replace("\\", "\\\\")
            .replace("\"", "\\\"").replace("$", "\\$")
        val dependencies = entries.filter { it.providerId != providerId.get() }.map { it.entryFqName } +
            additionalEntries.getOrElse(emptyList())
        val registrations = dependencies.distinct().joinToString("\n") { "    $it(registry)" }
        outputDirectory.get().asFile.deleteRecursively()
        val source = outputDirectory.file("${packageName.replace('.', '/')}/$functionName.kt").get().asFile
        source.parentFile.mkdirs()
        source.writeText(
            """
            @file:OptIn(com.kotlinorm.annotations.InternalKronosApi::class)

            /** Generated by the Kronos Gradle plugin; do not edit. */
            package $packageName

            import com.kotlinorm.utils.GeneratedTypeMetadataRegistry
            import com.kotlinorm.utils.GeneratedTypeProvider
            import com.kotlinorm.utils.GeneratedTypeRegistrar

            private class $providerName : GeneratedTypeProvider {
                override val id: String = "$providerLiteral"
                override fun contributeTo(registrar: GeneratedTypeRegistrar) {
                }
            }

            /**
             * Installs Native metadata for provider ${providerId.get()}.
             * Shared startup code should call initializeKronosMetadata().
             */
            @com.kotlinorm.annotations.InternalKronosApi
            public fun $functionName(registry: GeneratedTypeMetadataRegistry) {
                registry.register($providerName())
            }

            /** Low-level Native registration entry; shared startup should call initializeKronosMetadata(). */
            @com.kotlinorm.annotations.InternalKronosApi
            public fun $aggregateName(
                registry: GeneratedTypeMetadataRegistry = com.kotlinorm.utils.generatedTypeMetadataRegistry
            ) {
            @@DEPENDENCIES@@
                $functionName(registry)
            }
            """.trimIndent().replace("@@DEPENDENCIES@@", registrations) + "\n"
        )
        writeProjectionMetadataAnchor(functionName)
    }

    private fun writeProjectionMetadataAnchor(entryName: String) {
        val anchorName = "${entryName}ProjectionMetadataAnchor"
        val source = outputDirectory.file("com/kotlinorm/generated/projection/$anchorName.kt").get().asFile
        source.parentFile.mkdirs()
        source.writeText(
            """
            /** Generated by the Kronos Gradle plugin; do not edit. */
            package com.kotlinorm.generated.projection

            internal object $anchorName {}
            """.trimIndent() + "\n"
        )
    }
}

private val Identifier = Regex("[A-Za-z_][A-Za-z0-9_]*")
