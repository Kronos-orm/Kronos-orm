package com.kotlinorm.compiler.plugin

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Writes the source-visible Native metadata entry that the compiler plugin
 * fills with static descriptor registrations during Native IR generation.
 */
@CacheableTask
abstract class GenerateKronosNativeMetadataEntry : DefaultTask() {
    @get:Input
    abstract val entryFqName: Property<String>

    @get:Input
    abstract val providerId: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val fqName = entryFqName.get()
        val separator = fqName.lastIndexOf('.')
        require(separator > 0 && separator < fqName.lastIndex) {
            "Native metadata entry must be a top-level function fq-name: $fqName"
        }
        val packageName = fqName.substring(0, separator)
        val functionName = fqName.substring(separator + 1)
        require(functionName.matches(Identifier)) {
            "Native metadata entry must be a valid Kotlin identifier: $functionName"
        }
        val source = outputDirectory.file("${packageName.replace('.', '/')}/$functionName.kt").get().asFile
        source.parentFile.mkdirs()
        source.writeText(
            """
            /** Generated by the Kronos Gradle plugin; do not edit. */
            package $packageName

            import com.kotlinorm.utils.StaticTypeMetadataRegistry

            /**
             * Installs generated metadata for provider ${providerId.get()}.
             * The Kronos compiler plugin fills this body for Native targets.
             */
            public fun $functionName(registry: StaticTypeMetadataRegistry) {
            }
            """.trimIndent() + "\n"
        )
    }
}

private val Identifier = Regex("[A-Za-z_][A-Za-z0-9_]*")
