package com.kotlinorm.compiler.plugin

import java.nio.file.Files
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue
import org.gradle.testfixtures.ProjectBuilder

class GenerateKronosNativeMetadataEntryTest {
    @Test
    fun projectionAnchorTracksEntryIdentityAndRemovesRenamedOutputs() {
        val projectDir = Files.createTempDirectory("kronos-native-projection-anchor-test")
        try {
            val project = ProjectBuilder.builder().withProjectDir(projectDir.toFile()).build()
            val output = projectDir.resolve("generated")
            val task = project.tasks.create("generateEntry", GenerateKronosNativeMetadataEntry::class.java).apply {
                entryFqName.set("fixture.installMetadata")
                providerId.set("fixture:main")
                outputDirectory.set(output.toFile())
            }
            val anchor = output.resolve("com/kotlinorm/generated/projection/installMetadataProjectionMetadataAnchor.kt")
            task.generate()
            val expected = """
                /** Generated by the Kronos Gradle plugin; do not edit. */
                package com.kotlinorm.generated.projection

                internal object installMetadataProjectionMetadataAnchor {}
            """.trimIndent() + "\n"
            assertEquals(expected, Files.readString(anchor))
            task.generate()
            assertEquals(expected, Files.readString(anchor))

            task.entryFqName.set("fixture.renamedMetadata")
            task.generate()
            assertFalse(Files.exists(anchor))
            assertFalse(Files.exists(output.resolve("fixture/installMetadata.kt")))
            assertTrue(Files.isRegularFile(output.resolve("fixture/renamedMetadata.kt")))
            assertTrue(Files.isRegularFile(output.resolve(
                "com/kotlinorm/generated/projection/renamedMetadataProjectionMetadataAnchor.kt"
            )))
        } finally {
            Files.walk(projectDir).use { paths ->
                paths.sorted(Comparator.reverseOrder()).forEach(Files::deleteIfExists)
            }
        }
    }

    @Test
    fun writesSourceVisibleCommonEntry() {
        val projectDir = Files.createTempDirectory("kronos-native-entry-test")
        try {
            val project = ProjectBuilder.builder().withProjectDir(projectDir.toFile()).build()
            val output = projectDir.resolve("generated")
            val task = project.tasks.create(
                "generateKronosNativeMetadataEntry",
                GenerateKronosNativeMetadataEntry::class.java
            ).apply {
                entryFqName.set("com.kotlinorm.generated.native.installMetadata")
                providerId.set("gradle:com.example:sample::commonMain#0123456789abcdef")
                outputDirectory.set(output.toFile())
            }

            task.generate()

            val source = output.resolve("com/kotlinorm/generated/native/installMetadata.kt")
            assertTrue(Files.isRegularFile(source))
            assertEquals(
                """
                @file:OptIn(com.kotlinorm.annotations.InternalKronosApi::class)

                /** Generated by the Kronos Gradle plugin; do not edit. */
                package com.kotlinorm.generated.native

                import com.kotlinorm.utils.GeneratedTypeMetadataRegistry
                import com.kotlinorm.utils.GeneratedTypeProvider
                import com.kotlinorm.utils.GeneratedTypeRegistrar

                private class installMetadataProvider : GeneratedTypeProvider {
                    override val id: String = "gradle:com.example:sample::commonMain#0123456789abcdef"
                    override fun contributeTo(registrar: GeneratedTypeRegistrar) {
                    }
                }

                /**
                 * Installs Native metadata for provider gradle:com.example:sample::commonMain#0123456789abcdef.
                 * Shared startup code should call initializeKronosMetadata().
                 */
                @com.kotlinorm.annotations.InternalKronosApi
                public fun installMetadata(registry: GeneratedTypeMetadataRegistry) {
                    registry.register(installMetadataProvider())
                }

                /** Low-level Native registration entry; shared startup should call initializeKronosMetadata(). */
                @com.kotlinorm.annotations.InternalKronosApi
                public fun installMetadataDependencies(
                    registry: GeneratedTypeMetadataRegistry = com.kotlinorm.utils.generatedTypeMetadataRegistry
                ) {

                    installMetadata(registry)
                }
                """.trimIndent() + "\n",
                Files.readString(source)
            )
        } finally {
            Files.walk(projectDir).use { paths ->
                paths.sorted(Comparator.reverseOrder()).forEach(Files::deleteIfExists)
            }
        }
    }
}
