package com.kotlinorm.toolchain

import java.nio.file.Path

internal fun writeNativeMetadataEntry(
    entryFqName: String,
    providerId: String,
    additionalEntries: List<String>,
    dependencyMetadata: List<Path>,
    outputDirectory: Path
) {
        val fqName = entryFqName
        val separator = fqName.lastIndexOf('.')
        require(separator > 0 && separator < fqName.lastIndex) {
            "Native metadata entry must be a top-level function fq-name: $fqName"
        }
        val packageName = fqName.substring(0, separator)
        val functionName = fqName.substring(separator + 1)
        require(functionName.matches(Identifier)) {
            "Native metadata entry must be a valid Kotlin identifier: $functionName"
        }
        val entries = readNativeMetadataManifests(dependencyMetadata.map { it.toFile() }.toSet())
        val aggregateName = "${functionName}Dependencies"
        val providerName = "${functionName}Provider"
        val providerLiteral = providerId.replace("\\", "\\\\")
            .replace("\"", "\\\"").replace("$", "\\$")
        val dependencies = entries.filter { it.providerId != providerId }.map { it.entryFqName } +
            additionalEntries
        val registrations = dependencies.distinct().joinToString("\n") { "    $it(registry)" }
        outputDirectory.toFile().deleteRecursively()
        val source = outputDirectory.resolve("${packageName.replace('.', '/')}/$functionName.kt").toFile()
        source.parentFile.mkdirs()
        source.writeText(
            """
            @file:OptIn(com.kotlinorm.annotations.InternalKronosApi::class)

            /** Generated by the Kronos Kotlin Toolchain plugin; do not edit. */
            package $packageName

            import com.kotlinorm.utils.GeneratedTypeMetadataRegistry
            import com.kotlinorm.utils.GeneratedTypeProvider
            import com.kotlinorm.utils.GeneratedTypeRegistrar

            private class $providerName : GeneratedTypeProvider {
                override val id: String = "$providerLiteral"
                override fun contributeTo(registrar: GeneratedTypeRegistrar) {
                }
            }

            /**
             * Installs Native metadata for provider ${providerId}.
             * Shared startup code should call initializeKronosMetadata().
             */
            @com.kotlinorm.annotations.InternalKronosApi
            public fun $functionName(registry: GeneratedTypeMetadataRegistry) {
                registry.register($providerName())
            }

            /** Low-level Native registration entry; shared startup should call initializeKronosMetadata(). */
            @com.kotlinorm.annotations.InternalKronosApi
            public fun $aggregateName(
                registry: GeneratedTypeMetadataRegistry = com.kotlinorm.utils.generatedTypeMetadataRegistry
            ) {
            @@DEPENDENCIES@@
                $functionName(registry)
            }
            """.trimIndent().replace("@@DEPENDENCIES@@", registrations) + "\n"
        )
        writeProjectionMetadataAnchor(outputDirectory, functionName)
}

    private fun writeProjectionMetadataAnchor(outputDirectory: Path, entryName: String) {
        val anchorName = "${entryName}ProjectionMetadataAnchor"
        val source = outputDirectory.resolve("com/kotlinorm/generated/projection/$anchorName.kt").toFile()
        source.parentFile.mkdirs()
        source.writeText(
            """
            /** Generated by the Kronos Kotlin Toolchain plugin; do not edit. */
            package com.kotlinorm.generated.projection

            internal object $anchorName {}
            """.trimIndent() + "\n"
        )
    }

private val Identifier = Regex("[A-Za-z_][A-Za-z0-9_]*")
